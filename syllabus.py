LEVEL_ORDER = ["A0", "A1", "A2", "B1", "B2", "C1", "C2"]

def get_syllabus(level: str) -> dict:
    return SYLLABUS.get(level, SYLLABUS["A0"])

def next_level(level: str):
    try:
        i = LEVEL_ORDER.index(level)
    except ValueError:
        return None
    if i + 1 >= len(LEVEL_ORDER):
        return None
    return LEVEL_ORDER[i + 1]
